#!/usr/bin/env bash
# Install wheelhouse skills and agents for Claude Code, OpenCode and Pi.
# Works with bash 3.2 (macOS) and later. Run with --help for usage.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
MARK="generated by wheelhouse"
MARKER_FILE=".wheelhouse"
# get.sh writes VERSION into the download; a clone has only plugin.json.
WH_VERSION="$(cat "$REPO/VERSION" 2>/dev/null || sed -n 's/.*"version": *"\([^"]*\)".*/v\1/p' "$REPO/.claude-plugin/plugin.json")"

usage() {
  cat <<'EOF'
Usage: setup/install.sh [tools] [options]

Tools (default: auto-detect claude, opencode and pi on PATH):
  --claude          Claude Code  (~/.claude/skills, ~/.claude/agents)
  --opencode        OpenCode     (~/.config/opencode/{skills,commands,agents})
  --pi              Pi           (~/.pi/agent/skills)
  --all             All of the above

Options:
  --project DIR     Install into DIR/.claude, DIR/.opencode and DIR/.pi instead of
                    your home directory. Implies --copy unless --link is given.
  --copy            Copy files instead of symlinking them to this repo.
  --link            Symlink (default for global installs; `git pull` updates them).
  --force           Replace existing files that wheelhouse did not create.
  --dry-run         Print what would change without touching anything.
  --uninstall       Remove everything wheelhouse installed for the selected tools.
  -h, --help        Show this help.
EOF
}

TOOLS=""
PROJECT=""
MODE=""
FORCE=0
DRY=0
UNINSTALL=0

while [ $# -gt 0 ]; do
  case "$1" in
    --claude | --opencode | --pi) TOOLS="$TOOLS ${1#--}" ;;
    --all) TOOLS="claude opencode pi" ;;
    --project)
      [ $# -ge 2 ] || { echo "--project needs a directory" >&2; exit 2; }
      PROJECT="$2"
      shift
      ;;
    --copy) MODE="copy" ;;
    --link) MODE="link" ;;
    --force) FORCE=1 ;;
    --dry-run) DRY=1 ;;
    --uninstall) UNINSTALL=1 ;;
    -h | --help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

if [ -z "$TOOLS" ]; then
  for t in claude opencode pi; do
    if command -v "$t" >/dev/null 2>&1; then TOOLS="$TOOLS $t"; fi
  done
  if [ -z "$TOOLS" ]; then
    echo "No supported tool found on PATH. Pass --claude, --opencode, --pi or --all." >&2
    exit 1
  fi
fi

if [ -n "$PROJECT" ]; then
  [ -d "$PROJECT" ] || { echo "Project directory not found: $PROJECT" >&2; exit 1; }
  PROJECT="$(cd "$PROJECT" && pwd -P)"
  [ -n "$MODE" ] || MODE="copy"
  CLAUDE_SKILLS="$PROJECT/.claude/skills"
  CLAUDE_AGENTS="$PROJECT/.claude/agents"
  OC_SKILLS="$PROJECT/.opencode/skills"
  OC_COMMANDS="$PROJECT/.opencode/commands"
  OC_AGENTS="$PROJECT/.opencode/agents"
  OC_DATA="$PROJECT/.opencode/wheelhouse"
  PI_SKILLS="$PROJECT/.pi/skills"
else
  [ -n "$MODE" ] || MODE="link"
  OC_ROOT="${XDG_CONFIG_HOME:-$HOME/.config}/opencode"
  CLAUDE_SKILLS="$HOME/.claude/skills"
  CLAUDE_AGENTS="$HOME/.claude/agents"
  OC_SKILLS="$OC_ROOT/skills"
  OC_COMMANDS="$OC_ROOT/commands"
  OC_AGENTS="$OC_ROOT/agents"
  OC_DATA="$OC_ROOT/wheelhouse"
  PI_SKILLS="$HOME/.pi/agent/skills"
fi

has_tool() { case " $TOOLS " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

say() { printf '%s\n' "$*"; }
act() { if [ "$DRY" -eq 1 ]; then say "  would: $*"; else "$@"; fi; }

# --- frontmatter helpers -------------------------------------------------------

# Print the value of a single-line `key: value` from the first frontmatter block.
fm_get() {
  awk -v key="$2" '
    NR == 1 && $0 != "---" { exit }
    NR > 1 && $0 == "---" { exit }
    NR > 1 && index($0, key ":") == 1 {
      v = substr($0, length(key) + 2); sub(/^[ \t]+/, "", v); print v; exit
    }' "$1"
}

# Print everything after the closing frontmatter delimiter.
fm_body() { awk 'c >= 2 { print } $0 == "---" && c < 2 { c++ }' "$1"; }

# Quote a string as a YAML double-quoted scalar.
yaml_quote() {
  local s=$1
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  printf '"%s"' "$s"
}

is_manual() { [ "$(fm_get "$1" disable-model-invocation)" = "true" ]; }

# --- ownership -------------------------------------------------------------------

# True when PATH was created by wheelhouse: a symlink into this repo, a copied
# directory with our marker file, or a generated file carrying our mark.
is_ours() {
  local p=$1
  if [ -L "$p" ]; then
    case "$(readlink "$p")" in "$REPO"/*) return 0 ;; esac
    return 1
  fi
  if [ -d "$p" ]; then [ -f "$p/$MARKER_FILE" ]; return; fi
  # The mark sits right after the frontmatter, which is ~20 lines for OpenCode agents.
  if [ -f "$p" ]; then head -n 40 "$p" | grep -q "$MARK"; return; fi
  return 1
}

# Decide whether DEST may be (re)written. Prints a warning and fails if not.
claim() {
  local dest=$1
  if [ -e "$dest" ] || [ -L "$dest" ]; then
    if is_ours "$dest" || [ "$FORCE" -eq 1 ]; then
      act rm -rf "$dest"
    else
      say "  skip: $dest exists and was not created by wheelhouse (use --force to replace)"
      return 1
    fi
  fi
  return 0
}

place_dir() {
  local src=$1 dest=$2
  claim "$dest" || return 0
  act mkdir -p "$(dirname "$dest")"
  if [ "$MODE" = "link" ]; then
    act ln -s "$src" "$dest"
  else
    act cp -R "$src" "$dest"
    if [ "$DRY" -eq 0 ]; then printf '%s %s from %s\n' "$MARK" "$WH_VERSION" "$src" >"$dest/$MARKER_FILE"; fi
  fi
  say "  ok:   $dest"
}

# write_file DEST: content comes from stdin.
write_file() {
  local dest=$1 tmp
  tmp="$(mktemp)"
  cat >"$tmp"
  if claim "$dest"; then
    act mkdir -p "$(dirname "$dest")"
    act cp "$tmp" "$dest"
    say "  ok:   $dest"
  fi
  rm -f "$tmp"
}

remove_ours() {
  local p=$1
  if { [ -e "$p" ] || [ -L "$p" ]; } && is_ours "$p"; then
    act rm -rf "$p"
    say "  rm:   $p"
  fi
}

# --- inventory ---------------------------------------------------------------------

skill_dirs() { find "$REPO/skills" -mindepth 2 -maxdepth 2 -type d | sort; }
agent_files() { find "$REPO/agents" -mindepth 1 -maxdepth 1 -name '*.md' | sort; }

# --- renderers ---------------------------------------------------------------------

render_claude_agent() {
  local src=$1 name desc tools
  name="$(fm_get "$src" name)"
  desc="$(fm_get "$src" description)"
  tools="Read, Grep, Glob, Bash"
  if [ "$(fm_get "$src" web)" = "true" ]; then tools="$tools, WebFetch, WebSearch"; fi
  printf -- '---\nname: %s\ndescription: %s\ntools: %s\n---\n' "$name" "$(yaml_quote "$desc")" "$tools"
  printf '<!-- %s from agents/%s.md; edit the source and re-run setup/install.sh -->\n' "$MARK" "$name"
  fm_body "$src"
}

render_opencode_agent() {
  local src=$1 name desc web
  name="$(fm_get "$src" name)"
  desc="$(fm_get "$src" description)"
  web="deny"
  if [ "$(fm_get "$src" web)" = "true" ]; then web="allow"; fi
  cat <<EOF
---
description: $(yaml_quote "$desc")
mode: subagent
permission:
  edit: deny
  task: deny
  webfetch: $web
  bash:
    "*": ask
    "git status*": allow
    "git diff*": allow
    "git log*": allow
    "git show*": allow
    "git merge-base*": allow
    "git rev-parse*": allow
---
<!-- $MARK from agents/$name.md; edit the source and re-run setup/install.sh -->
EOF
  fm_body "$src"
}

# OpenCode ignores disable-model-invocation and has no slash command for skills,
# so manual-only workflows become commands that embed the skill body.
render_opencode_command() {
  local src=$1 refdir=$2 name desc
  name="$(fm_get "$src" name)"
  desc="$(fm_get "$src" description)"
  printf -- '---\ndescription: %s\n---\n' "$(yaml_quote "$desc")"
  printf '<!-- %s from skills/workflow/%s; edit the source and re-run setup/install.sh -->\n' "$MARK" "$name"
  if [ -d "$refdir/references" ]; then
    printf '> Files under `references/` mentioned below are in `%s/references/`.\n' "$refdir"
  fi
  fm_body "$src"
  printf '\n## Input\n\n$ARGUMENTS\n'
}

render_opencode_stub() {
  local src=$1 name desc
  name="$(fm_get "$src" name)"
  desc="$(fm_get "$src" description)"
  printf -- '---\ndescription: %s\n---\n' "$(yaml_quote "$desc")"
  printf '<!-- %s; edit the source and re-run setup/install.sh -->\n' "$MARK"
  printf 'Load the `%s` skill and follow it for this input:\n\n$ARGUMENTS\n' "$name"
}

# --- per-tool install ----------------------------------------------------------------

install_claude() {
  say "Claude Code"
  local d f
  while IFS= read -r d; do place_dir "$d" "$CLAUDE_SKILLS/$(basename "$d")"; done < <(skill_dirs)
  while IFS= read -r f; do render_claude_agent "$f" | write_file "$CLAUDE_AGENTS/$(basename "$f")"; done < <(agent_files)
}

install_opencode() {
  say "OpenCode"
  local d f name refdir
  while IFS= read -r d; do
    name="$(basename "$d")"
    f="$d/SKILL.md"
    if is_manual "$f"; then
      refdir="$d"
      if [ "$MODE" = "copy" ]; then
        place_dir "$d" "$OC_DATA/$name"
        refdir="$OC_DATA/$name"
      fi
      render_opencode_command "$f" "$refdir" | write_file "$OC_COMMANDS/$name.md"
    else
      place_dir "$d" "$OC_SKILLS/$name"
      case "$d" in
        "$REPO/skills/workflow/"*) render_opencode_stub "$f" | write_file "$OC_COMMANDS/$name.md" ;;
      esac
    fi
  done < <(skill_dirs)
  while IFS= read -r f; do render_opencode_agent "$f" | write_file "$OC_AGENTS/$(basename "$f")"; done < <(agent_files)
  if has_tool claude || [ -L "$CLAUDE_SKILLS/lead" ] || [ -f "$CLAUDE_SKILLS/lead/$MARKER_FILE" ]; then
    cat <<'EOF'
  note: OpenCode also reads .claude/skills, where the manual-only workflows (lead, story,
        pair, deliver, accept) are installed for Claude Code. OpenCode 2 honours their
        disable-model-invocation flag. OpenCode 1 ignores it; the workflows still refuse to
        run unless invoked, but to hide them from OpenCode 1 completely set:
          export OPENCODE_DISABLE_CLAUDE_CODE_SKILLS=1
EOF
  fi
}

install_pi() {
  say "Pi"
  local d
  while IFS= read -r d; do place_dir "$d" "$PI_SKILLS/$(basename "$d")"; done < <(skill_dirs)
  say "  note: Pi has no built-in subagents. verify asks for a fresh session instead,"
  say "        and lead investigates inline. Invoke workflows as /skill:<name>."
}

uninstall_tool() {
  local tool=$1 d f name
  say "Uninstall: $tool"
  while IFS= read -r d; do
    name="$(basename "$d")"
    case "$tool" in
      claude) remove_ours "$CLAUDE_SKILLS/$name" ;;
      opencode)
        remove_ours "$OC_SKILLS/$name"
        remove_ours "$OC_COMMANDS/$name.md"
        remove_ours "$OC_DATA/$name"
        ;;
      pi) remove_ours "$PI_SKILLS/$name" ;;
    esac
  done < <(skill_dirs)
  while IFS= read -r f; do
    case "$tool" in
      claude) remove_ours "$CLAUDE_AGENTS/$(basename "$f")" ;;
      opencode) remove_ours "$OC_AGENTS/$(basename "$f")" ;;
    esac
  done < <(agent_files)
  if [ "$tool" = "opencode" ] && [ -d "$OC_DATA" ] && [ -z "$(ls -A "$OC_DATA")" ]; then
    act rmdir "$OC_DATA"
  fi
}

say "wheelhouse: $REPO"
say "tools:${TOOLS} · mode: $MODE${PROJECT:+ · project: $PROJECT}$([ "$DRY" -eq 1 ] && printf ' · dry run')"

for t in $TOOLS; do
  if [ "$UNINSTALL" -eq 1 ]; then
    uninstall_tool "$t"
  else
    "install_$t"
  fi
done
